"""Records the app's sentences and words with Kokoro-82M (Apache-2.0), an open neural voice model run on this machine.

Setup (once):
  python3 -m venv venv && venv/bin/pip install --only-binary=:all: spacy && venv/bin/pip install kokoro-onnx soundfile misaki num2words
  venv/bin/pip install --no-deps en_core_web_sm  (wheel from huggingface.co/spacy/en_core_web_sm)
  model dir: model.onnx (onnx/model.onnx) and voices/<name>.bin from huggingface.co/onnx-community/Kokoro-82M-v1.0-ONNX
Run:
  node tools/tts/dump.js > items.json
  venv/bin/python tools/tts/gen.py --model DIR --items items.json
Only missing clips are recorded, so re-running after adding content is quick. Writes audio/<key>-<voice>.m4a and audio/manifest.js.
"""
import argparse, glob, json, os, subprocess, sys, tempfile, warnings
import numpy as np, soundfile as sf
warnings.filterwarnings("ignore")

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
VOICES = json.load(open(os.path.join(os.path.dirname(__file__), "voices.json")))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True, help="dir with model.onnx and voices/*.bin")
    ap.add_argument("--items", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "audio"))
    ap.add_argument("--redo", default="", help="comma-separated keys to record again")
    ap.add_argument("--prune", action="store_true", help="delete clips no longer in items")
    a = ap.parse_args()
    from kokoro_onnx import Kokoro
    from misaki import en
    npz = os.path.join(tempfile.mkdtemp(), "voices.npz")
    np.savez(npz, **{os.path.basename(f)[:-4]: np.fromfile(f, dtype=np.float32).reshape(-1, 1, 256) for f in glob.glob(os.path.join(a.model, "voices", "*.bin"))})
    tts = Kokoro(os.path.join(a.model, "model.onnx"), npz)
    g2p = {"us": en.G2P(trf=False, british=False, fallback=espeak_fallback(False)), "gb": en.G2P(trf=False, british=True, fallback=espeak_fallback(True))}
    items = json.load(open(a.items)); redo = set(filter(None, a.redo.split(",")))
    os.makedirs(a.out, exist_ok=True); todo = [(it, v) for it in items for v in it["voices"]]
    made = 0
    for n, (it, v) in enumerate(todo):
        path = os.path.join(a.out, f"{it['key']}-{v}.m4a")
        if os.path.exists(path) and it["key"] not in redo: continue
        voice = VOICES[v]; uk = voice[0] == "b"
        ph = g2p["gb" if uk else "us"](it.get("say", it["text"]))[0]
        audio, sr = tts.create(ph, voice=voice, speed=it.get("speed", 1.0), lang="en-gb" if uk else "en-us", is_phonemes=True)
        audio = shape(np.asarray(audio, dtype=np.float32), sr)
        with tempfile.NamedTemporaryFile(suffix=".wav") as w:
            sf.write(w.name, audio, sr)
            subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", w.name, "-ac", "1", "-c:a", "aac", "-b:a", "40k", "-movflags", "+faststart", path], check=True)
        made += 1
        if made % 50 == 0: print(f"{n+1}/{len(todo)}", flush=True)
    if a.prune:
        keep = {f"{it['key']}-{v}.m4a" for it in items for v in it["voices"]}
        gone = [f for f in os.listdir(a.out) if f.endswith(".m4a") and f not in keep]
        for f in gone: os.remove(os.path.join(a.out, f))
        print(f"pruned {len(gone)}")
    manifest = {it["key"]: "".join(str(v) for v in it["voices"]) for it in items if all(os.path.exists(os.path.join(a.out, f"{it['key']}-{v}.m4a")) for v in it["voices"])}
    with open(os.path.join(a.out, "manifest.js"), "w") as f:
        f.write("/* generated by tools/tts/gen.py: sentence key (chunkId of the text) -> voices recorded, as indexes into AUDIO_VOICES. File: audio/<key>-<voice>.m4a */\n")
        f.write("const AUDIO_VOICES = " + json.dumps(VOICES) + ";\n")
        f.write("const AUDIO = " + json.dumps(manifest, separators=(",", ":")) + ";\n")
        mb = sum(os.path.getsize(os.path.join(a.out, f"{k}-{v}.m4a")) for k, vs in manifest.items() for v in vs) / 1e6
        f.write(f"const AUDIO_MB = {mb:.0f};\n")
    print(f"recorded {made}, manifest {len(manifest)} items")

def espeak_fallback(british):
    """words misaki's dictionary lacks (brand names, rare words) are spelled out by eSpeak NG"""
    import espeakng_loader
    from phonemizer.backend.espeak.wrapper import EspeakWrapper
    EspeakWrapper.set_library(espeakng_loader.get_library_path()); EspeakWrapper.set_data_path(espeakng_loader.get_data_path())
    from misaki import espeak
    return espeak.EspeakFallback(british=british)

def shape(x, sr):
    """trim silence to ~80 ms each side, even out loudness (RMS of voiced part to -19 dBFS, peaks under -1 dBFS), soft edges"""
    thr = 10 ** (-45 / 20); idx = np.where(np.abs(x) > thr)[0]
    if len(idx): pad = int(.08 * sr); x = x[max(0, idx[0] - pad): idx[-1] + pad]
    voiced = x[np.abs(x) > thr]; rms = np.sqrt(np.mean(voiced ** 2)) if len(voiced) else 0
    if rms > 0: x = x * (10 ** (-19 / 20) / rms)
    peak = np.max(np.abs(x)) if len(x) else 0
    if peak > 10 ** (-1 / 20): x = x * (10 ** (-1 / 20) / peak)
    f = min(len(x) // 4, int(.01 * sr))
    if f: ramp = np.linspace(0, 1, f); x[:f] *= ramp; x[-f:] *= ramp[::-1]
    return x

if __name__ == "__main__":
    sys.exit(main())
