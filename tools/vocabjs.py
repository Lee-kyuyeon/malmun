#!/usr/bin/env python3
"""Writes content-vocab.js from the outputs of tools/vocabtest.py and tools/wordnet.py.
Usage: python3 tools/vocabjs.py vocabtest.json syn.json > content-vocab.js"""
import json, sys
vt, syn = json.load(open(sys.argv[1])), json.load(open(sys.argv[2]))
j = lambda o: json.dumps(o, ensure_ascii=False, separators=(",", ":"))
print("""/* 재잘 · vocabulary data generated by tools/ — do not edit by hand.
   VOCAB_TEST, VOCAB_RANK: tools/vocabtest.py — frequencies from wordfreq (Robyn Speer, CC BY-SA 4.0), lemmas from Princeton WordNet 3.0.
   SYN: tools/wordnet.py — synonyms/antonyms from Princeton WordNet 3.0 (WordNet licence), reviewed by hand (tools/data/syn-review.txt). */""")
print("const VOCAB_TEST = " + j({"bands": vt["bands"], "fakes": vt["fakes"]}) + ";")
print("const VOCAB_RANK = " + j(vt["rank"]) + ";")
print("const SYN = " + j(syn) + ";")
